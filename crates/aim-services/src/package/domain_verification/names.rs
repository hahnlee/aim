use std::cmp::Ordering;

pub fn fold(unit: u16) -> u16 {
    let at = FOLD.partition_point(|&(_, end, _, _)| end < unit);
    match FOLD.get(at) {
        Some(&(start, _, stride, delta)) if start <= unit && (unit - start) % stride == 0 => {
            (i32::from(unit) + delta) as u16
        }
        _ => unit,
    }
}

pub fn compare(first: &str, second: &str) -> Ordering {
    first
        .encode_utf16()
        .map(fold)
        .cmp(second.encode_utf16().map(fold))
}

