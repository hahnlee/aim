        assert!(PATCHED_RUNTIME_SOURCES.contains(&"runtime.cc"));
        assert!(PATCHED_RUNTIME_SOURCES.contains(&"plugin.cc"));
        assert!(PATCHED_RUNTIME_SOURCES.contains(&"runtime.h"));
        assert!(PATCHED_RUNTIME_SOURCES.contains(&"jit/jit.cc"));
